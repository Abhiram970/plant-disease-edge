TO_SUPPLY = r"\textbf{[TO SUPPLY: %s]}"


def _squash(s: str) -> str:
    """Collapse whitespace the way LaTeX does, for wrapping-insensitive comparison."""
    return " ".join(s.split())


class Edit:
    """One exact-string replacement with a human-readable justification."""

    def __init__(self, ident: str, path: Path, old: str, new: str, why: str) -> None:
        self.ident = ident
        self.path = path
        self.old = old.strip("\n")
        self.new = new.strip("\n")
        self.why = why

    def status(self, text: str) -> str:
        # ORDER MATTERS. Several edits insert text around their anchor rather than
        # replacing it outright (C1, C3b, C4 and D1 all keep the anchor sentence and add
        # to it), so the anchor is still present after a successful pass. Testing `old`
        # first would report "apply" on a re-run and duplicate whole paragraphs. The
        # replacement is therefore the authority on whether the edit has landed.
        #
        # The test ignores line wrapping: LaTeX treats any run of whitespace as a single
        # space, so re-flowing a patched paragraph must not make this look unapplied. The
        # forward match stays exact, because the replacement has to be byte-precise.
        if _squash(self.new) in _squash(text):
            return "already"
        n_old = text.count(self.old)
        if n_old == 1:
            return "apply"
        if n_old > 1:
            raise SystemExit(
                f"[{self.ident}] anchor is ambiguous ({n_old} matches) in "
                f"{self.path.name}; narrow the anchor before re-running."
            )
        raise SystemExit(
            f"[{self.ident}] anchor not found in {self.path.name}, and the replacement "
            f"is not present either -- the source has drifted.\n"
            f"--- expected ---\n{self.old[:500]}"
        )


EDITS: list[Edit] = []


def edit(ident: str, path: Path, old: str, new: str, why: str) -> None:
    EDITS.append(Edit(ident, path, old, new, why))


