def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true", help="report without writing")
    args = ap.parse_args()

    for p in SOURCES:
        if not p.exists():
            raise SystemExit(f"missing source file: {p}")

    texts = {p: p.read_text(encoding="utf-8") for p in SOURCES}

    # patch_rerun_2026-09-11.py rewrote the abstract and contribution 2 on top of two of
    # the edits below, so those anchors are legitimately gone. This script is a historical
    # record of what the 2026-09-10 audit changed, not a re-runnable migration; say so
    # instead of aborting with "the source has drifted", which reads like a real problem.
    if "A de-duplicated re-run at all three scales" in texts[MAIN]:
        print("SUPERSEDED: patch_rerun_2026-09-11.py has revised the scaling claim on top of\n"
              "these edits. This script is kept as the record of the 2026-09-10 pass; it is\n"
              "not re-runnable against the current source. Nothing was changed.")
        return 0

    # Resolve every edit against the ORIGINAL text before writing anything, so a late
    # failure cannot leave the tree half-patched.
    plan = [(e, e.status(texts[e.path])) for e in EDITS]

    for e, st in plan:
        if st == "apply":
            texts[e.path] = texts[e.path].replace(e.old, e.new, 1)

    applied = [e for e, s in plan if s == "apply"]
    skipped = [e for e, s in plan if s == "already"]

    if not args.dry_run:
        for p, t in texts.items():
            # newline="" prevents Windows CRLF translation. The manuscript is LF-only and
            # a previous pass shipped 1,011 CR bytes into main.tex this way.
            with open(p, "w", encoding="utf-8", newline="") as fh:
                fh.write(t)

    verb = "would apply" if args.dry_run else "applied"
    print(f"{verb} {len(applied)}/{len(EDITS)} edits; {len(skipped)} already present\n")
    for e, st in plan:
        print(f"  [{st:7s}] {e.ident:30s} {e.why}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
