"""
Build results/ — a browsable archive of every experiment output, with full epoch logs.

WHY: docs/paper/ is a flat working set that the table/figure generators read. It is not pleasant to
browse, and results/ was git-ignored entirely, so nobody outside this machine could see any of the
numbers. This organises every result JSON by experiment, keeps the per-epoch training curves intact,
and writes results/README.md as an index with summary tables.

GENERATED — do not hand-edit results/. Re-run this after any new result lands.

    python scripts/collect_results.py
"""
from __future__ import annotations
import json
import shutil
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import config as C

SRC = C.REPO_ROOT / "docs" / "paper"
DST = C.REPO_ROOT / "results"

# (subfolder, glob, human description)
GROUPS = [
    ("supervised", "supervised_*.json",
     "Supervised CNN baselines — one protocol (166 classes, 8 epochs). Full per-epoch loss and "
     "test accuracy retained in `epoch_log`."),
    ("zeroshot", "zeroshot_eval_*.json",
     "Cross-crop zero-shot at three nested scales (A/B/C), 4 descriptor strategies x 5 encoders. "
     "`*_clean` is the label-corrected sensitivity run."),
    ("abstain", "metrics_abstain_*.json",
     "Top-5 and risk–coverage / AURC for the abstain gate."),
    ("probe_seen", "probe_seen_*.json",
     "Seen-crop linear probe on the frozen VLM backbones, at all three scales."),
    ("wiseft", "run_all_exp3_*.json",
     "WiSE-FT alpha sweep — the seen/unseen trade-off dial."),
    ("bakeoff", "run_all_bakeoff.json",
     "Encoder bake-off, including the domain/biological foundation models."),
    ("hybrid", "run_all_train_seen_*.json",
     "Hybrid check: trained seen head vs preserved unseen zero-shot on one frozen backbone."),
    ("loco", "loco_*.json",
     "Leave-one-crop-out with bootstrap 95% CIs (anti-cherry-pick)."),
    ("edge", "edge_*.json",
     "On-device latency/size per tier, plus the INT8 graph diagnosis."),
    ("phase0", "phase0_*.json",
     "Phase-0 de-risk spikes: the distillation and specialisation attempts that failed."),
]


def pct(x):
    return "—" if x is None else f"{x * 100:.1f}%"


def main():
    if DST.exists():
        for p in sorted(DST.rglob("*.json")):
            if "onnx" not in p.parts:
                p.unlink()
    DST.mkdir(parents=True, exist_ok=True)

    out = [
        "# results/ — every experiment output",
        "",
        f"> **Generated by `scripts/collect_results.py` on {date.today().isoformat()}. "
        f"Do not hand-edit.**",
        "> Canonical copies live in `docs/paper/`, which the table and figure generators read; this "
        "folder is the browsable view. Per-epoch training curves are preserved in `epoch_log`.",
        "",
        "Exported ONNX graphs (~1.7 GB) are deliberately not tracked — regenerate them with "
        "`python kaggle/benchmark_quantization.py`.",
        "",
    ]

    counts = {}
    for sub, pattern, desc in GROUPS:
        files = sorted(SRC.glob(pattern))
        if not files:
            continue
        d = DST / sub
        d.mkdir(parents=True, exist_ok=True)
        for f in files:
            shutil.copy(f, d / f.name)
        counts[sub] = len(files)
        out.append(f"## `{sub}/` — {len(files)} file(s)")
        out.append("")
        out.append(desc)
        out.append("")

        if sub == "supervised":
            rows = []
            for f in files:
                j = json.loads(f.read_text(encoding="utf-8"))
                rows.append((j.get("arch"), j.get("params_M"), j.get("seen_top1"),
                             j.get("seen_classes"), len(j.get("epoch_log") or [])))
            out.append("| Architecture | Params (M) | Classes | Epochs | Seen top-1 | Unseen |")
            out.append("|---|---|---|---|---|---|")
            for a, pm, acc, ncls, ne in sorted(rows, key=lambda r: -(r[2] or 0)):
                out.append(f"| `{a}` | {'—' if pm is None else f'{pm:.2f}'} | {ncls} | {ne} "
                           f"| **{pct(acc)}** | 0 (structural) |")
            out.append("")
            out.append("<details><summary>Per-epoch training curves (all architectures)</summary>")
            out.append("")
            for f in files:
                j = json.loads(f.read_text(encoding="utf-8"))
                log = j.get("epoch_log") or []
                if not log:
                    continue
                out.append(f"**{j.get('arch')}**")
                out.append("")
                out.append("| Epoch | Train loss | Test top-1 |")
                out.append("|---|---|---|")
                for e in log:
                    out.append(f"| {e.get('epoch', 0) + 1} | {e.get('loss')} "
                               f"| {pct(e.get('test_top1'))} |")
                out.append("")
            out.append("</details>")
            out.append("")

        elif sub == "zeroshot":
            out.append("| File | Classes | Chance | Encoders |")
            out.append("|---|---|---|---|")
            for f in files:
                j = json.loads(f.read_text(encoding="utf-8"))
                out.append(f"| `{f.name}` | {j.get('n_classes')} | {pct(j.get('chance'))} "
                           f"| {len(j.get('models', {}))} |")
            out.append("")

        elif sub == "probe_seen":
            out.append("| Config | Seen crops | Seen classes | Seen images | Encoders |")
            out.append("|---|---|---|---|---|")
            for f in files:
                j = json.loads(f.read_text(encoding="utf-8"))
                n = j.get("seen_images")
                out.append(f"| {j.get('exp')} | {j.get('n_seen_crops', '—')} "
                           f"| {j.get('seen_classes')} | {'—' if n is None else f'{n:,}'} "
                           f"| {len(j.get('models', {}))} |")
            out.append("")
        else:
            out.append("Files: " + ", ".join(f"`{f.name}`" for f in files))
            out.append("")

    # non-JSON artefacts worth keeping alongside
    for extra in ("edge_quant_benchmark.md",):
        src = SRC / extra
        if src.exists():
            shutil.copy(src, DST / "edge" / extra)

    (DST / "README.md").write_text("\n".join(out), encoding="utf-8")
    total = sum(counts.values())
    print(f"[results] archived {total} JSON files into {DST}")
    for k, v in counts.items():
        print(f"    {k:12s} {v}")
    print(f"[results] wrote {DST / 'README.md'}")


if __name__ == "__main__":
    main()
